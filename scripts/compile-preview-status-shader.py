"""Compile the tiny preview-status shader at development time (SM4)."""
from pathlib import Path
import ctypes
import hashlib

root=Path(__file__).resolve().parents[1]
source=b'''SamplerState sampler0 : register(s0);
Texture2D texture0 : register(t0);
struct PS_INPUT { float4 pos : SV_POSITION; float4 col : COLOR0; float2 uv : TEXCOORD0; };
float4 main(PS_INPUT input) : SV_Target {
 float mask=texture0.Sample(sampler0,input.uv).a;
 if(input.col.r<0.5) {
  uint width,height; texture0.GetDimensions(width,height);
  float2 pixel=1.0/float2(width,height);
  float edge=max(max(texture0.Sample(sampler0,input.uv+float2(pixel.x,0)).a,texture0.Sample(sampler0,input.uv-float2(pixel.x,0)).a),max(texture0.Sample(sampler0,input.uv+float2(0,pixel.y)).a,texture0.Sample(sampler0,input.uv-float2(0,pixel.y)).a));
  return float4(0,0,0,saturate(edge-mask)*input.col.a);
 }
 float coverage=input.col.a*mask;
 return float4(coverage,coverage,coverage,coverage);
}'''
directory=ctypes.create_unicode_buffer(32768)
ctypes.windll.kernel32.GetSystemDirectoryW(directory,len(directory))
compiler=ctypes.WinDLL(str(Path(directory.value)/'D3DCompiler_47.dll'))
compile=compiler.D3DCompile
compile.argtypes=[ctypes.c_void_p,ctypes.c_size_t,ctypes.c_char_p,ctypes.c_void_p,ctypes.c_void_p,ctypes.c_char_p,ctypes.c_char_p,ctypes.c_uint,ctypes.c_uint,ctypes.POINTER(ctypes.c_void_p),ctypes.POINTER(ctypes.c_void_p)]
compile.restype=ctypes.c_long
def data(blob):
 table=ctypes.cast(blob,ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
 get=ctypes.WINFUNCTYPE(ctypes.c_void_p,ctypes.c_void_p)(table[3]);size=ctypes.WINFUNCTYPE(ctypes.c_size_t,ctypes.c_void_p)(table[4]);release=ctypes.WINFUNCTYPE(ctypes.c_ulong,ctypes.c_void_p)(table[2])
 result=ctypes.string_at(get(blob),size(blob));release(blob);return result
code=ctypes.c_void_p();error=ctypes.c_void_p();buffer=ctypes.create_string_buffer(source)
result=compile(buffer,len(source),None,None,None,b'main',b'ps_4_0',0,0,ctypes.byref(code),ctypes.byref(error))
if result<0:raise RuntimeError(data(error).decode() if error else 'Shader compilation failed')
if error:data(error)
compiled=data(code);assert compiled.startswith(b'DXBC')
rows=[', '.join(f'0x{v:02x}' for v in compiled[i:i+16]) for i in range(0,len(compiled),16)]
out='#pragma once\n// Own SM4 shader; generated by scripts/compile-preview-status-shader.py.\n'
out+='// Source SHA256 '+hashlib.sha256(source).hexdigest()+'\nnamespace psui {\ninline constexpr unsigned char preview_status_shader[]={\n '+',\n '.join(rows)+'\n};\n}\n'
(root/'native/ui/include/psui/preview_status_shader.hpp').write_text(out,encoding='utf-8')
print('Generated preview-status SM4 bytecode; no runtime compiler dependency.')
